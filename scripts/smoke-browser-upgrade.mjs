import assert from 'node:assert/strict'

export async function smokeBrowserUpgrade({ page, context, base, open, pass, incoming, channelName }) {
  let settings = await open('Settings', '.synnical-settings-app')
  await settings.getByRole('button', { name: 'Appearance', exact: true }).click()
  await settings.getByRole('radio', { name: /^light$/i }).check()
  await page.waitForFunction(() => document.documentElement.dataset.appearance === 'light')
  await page.screenshot({ path: '/tmp/synnical-light.png' })
  const light = await settings.evaluate(el => ({ color: getComputedStyle(el).color, background: getComputedStyle(el).backgroundColor }))
  assert.notEqual(light.color, light.background)
  await page.waitForFunction(async () => (await (await fetch('/api/features/settings')).json()).settings['appearance.mode'] === 'light')
  await page.reload({ waitUntil: 'domcontentloaded' }); await page.locator('.synnical-os-root').waitFor()
  await page.waitForFunction(() => document.documentElement.dataset.appearance === 'light')
  settings = await open('Settings', '.synnical-settings-app')
  await settings.getByRole('button', { name: 'Appearance', exact: true }).click()
  await settings.getByRole('radio', { name: /^dark$/i }).check()
  await page.waitForFunction(() => document.documentElement.dataset.appearance === 'dark')
  const bad = await settings.locator('input:not([type=password])').evaluateAll(inputs => inputs.filter(input => ['username','password','login'].includes(input.name)).map(input => input.name))
  assert.deepEqual(bad, [])
  assert.equal(await page.getByText('Exit OS Mode', { exact: true }).count(), 0)
  pass('upgrade Chromium: Light/Dark persists through API/reload; settings use non-credential names; OS-only shell')

  await page.evaluate(() => { window.__osNotices = []; window.__browserNotices = []; window.addEventListener('synnical-os-notify', event => window.__osNotices.push(event.detail)); window.Notification = class { static permission = 'granted'; constructor(title, options) { window.__browserNotices.push({title,options}) } } })
  await context.request.post(base + '/api/features/settings', { data: { settings: { 'notifications.desktop': true } } })
  await page.evaluate(() => { localStorage.setItem('synnical:settings:notifications.desktop', 'true'); window.dispatchEvent(new Event('synnical-settings-changed')) })
  await incoming('ordinary')
  await page.getByLabel('Unread messages', { exact: true }).first().waitFor()
  assert.equal(await page.evaluate(() => window.__osNotices.length), 0)
  assert.equal(await page.evaluate(() => window.__browserNotices.length), 0)
  await incoming('mention')
  await page.waitForFunction(() => window.__osNotices.length === 1)
  await page.getByLabel('Unread mention', { exact: true }).first().waitFor()
  assert.equal(await page.evaluate(() => window.__browserNotices.length), 1)
  await incoming('dm')
  assert.equal(await page.evaluate(() => window.__osNotices.length), 1)
  assert.equal(await page.evaluate(() => window.__browserNotices.length), 1)
  pass('upgrade Chromium: closed Chat receives unread channel/DM dots; only resolved mentions create OS/browser notifications')

  const chat = await open('Chat', '.synnical-os-window:has(input[placeholder^="Message #"])')
  await chat.getByRole('button', { name: channelName, exact: true }).first().click()
  const composer = chat.locator('input[placeholder^="Message #"]')
  await composer.waitFor()
  await page.waitForFunction(() => document.querySelector('input[placeholder^="Message #"]')?.disabled === false)
  await page.waitForFunction(() => document.querySelectorAll('.message-group').length >= 30)
  await page.evaluate(() => { window.__messageMutations = 0; window.__messageObserver = new MutationObserver(records => { window.__messageMutations += records.filter(row => row.type === 'childList').length }); document.querySelectorAll('.message-group').forEach(el => window.__messageObserver.observe(el, { childList: true, subtree: true })) })
  const text = 'Typing remains immediate while a real conversation is loaded. '.repeat(3)
  const started = Date.now(); await composer.pressSequentially(text, { delay: 0 }); const elapsed = Date.now() - started
  assert.equal(await composer.inputValue(), text)
  assert.equal(await page.evaluate(() => window.__messageMutations), 0, 'Typing must not rebuild the loaded message DOM')
  await page.evaluate(() => window.__messageObserver.disconnect())
  await composer.fill('')
  pass(`upgrade Chromium: ${text.length} typed characters retained, no message DOM rebuild (${elapsed}ms automation duration)`)
  const image = chat.locator('[data-image-viewer]').first()
  await image.click()
  const viewer = page.getByRole('dialog', { name: 'Image viewer' }); await viewer.waitFor()
  await viewer.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await viewer.getByText('125%', { exact: true }).waitFor()
  await viewer.getByRole('button', { name: 'Reset zoom', exact: true }).click()
  await viewer.getByText('100%', { exact: true }).waitFor()
  await page.keyboard.press('Escape'); await viewer.waitFor({ state: 'hidden' })
  pass('upgrade Chromium: persisted uploaded image opens in shared viewer; zoom/reset/ESC work')
  await open('SynnVM', '.synnical-os-window:has-text("Coming Soon")')
  assert.equal(await page.locator('.synnical-os-window iframe').count(), 0)
  pass('upgrade Chromium: SynnVM launches intentional Coming Soon screen')
}
